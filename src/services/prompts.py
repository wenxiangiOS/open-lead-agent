def get_main_dialogue(
    gender_instruction: str = "",
    collected_info: str = "",
    contact_instruction: str = "",
    skipped_fields_instruction: str = "",
    ask_count_instruction: str = "",
    non_response_count: int = 0,
    is_first_chat: bool = True
) -> str:
    """获取主对话提示词"""
    import logging
    logger = logging.getLogger(__name__)

    # 根据无效回复次数添加额外提示
    non_response_prompt = ""
    if non_response_count > 0:
        non_response_prompt = f"\n\n【注意】用户已连续{non_response_count}次只回确认词（如'嗯'、'好'）但没有提供任何信息。这说明用户可能不想回答或没听懂。"
        if non_response_count >= 2:
            non_response_prompt += "请暂时跳过刚才问的问题，换其他问题问，不要重复问同样的话！"

    dialogue_text = MAIN_DIALOGUE.format(
        CORE_PERSONALITY=CORE_PERSONALITY,
        gender_instruction=gender_instruction,
        collected_info=collected_info,
        contact_instruction=contact_instruction,
        skipped_fields_instruction=skipped_fields_instruction  # 不再在这里添加 ask_count_instruction
    )

    # 构建开头强制指令
    forced_instruction = ""

    # 1. 智能追问提示（最高优先级，放在最前面）
    if ask_count_instruction:
        forced_instruction += ask_count_instruction
        logger.info(f"[提示词修改] 已添加智能追问提示到开头")

    # 2. 如果不是首次对话，添加禁止开场白的指令
    if not is_first_chat:
        forced_instruction += """
【⚠️⚠️⚠️最高优先级指令⚠️⚠️⚠️】用户已经有资料了！绝对禁止显示开场白！
- 【禁止行为】严禁说"我是小缘"、"怎么称呼你"、"我是同城脱单联盟"、"我该怎么称呼你"
- 【禁止行为】严禁说"你好呀"、"你好"等开场问候语！用户已经有资料了，不需要再打招呼！
- 【必须行为】直接用性别称呼 + 自然地问1-2个未收集字段
- 【示例1】已收集：啊鬼,男,25岁 → 回复："嗯嗯～小哥哥在哪个城市呢？是做什么工作的呀？"
- 【示例2】已收集：青青,男,36岁,深圳,本科 → 回复："好的呢～小哥哥身高体重多少呀？"

【重要】请根据【已收集】后面的信息，识别已收集的字段，只询问未收集的字段！
"""
        logger.info(f"[提示词修改] 已添加禁止开场白指令，is_first_chat={is_first_chat}")

    # 将强制指令添加到提示词开头
    if forced_instruction:
        dialogue_text = forced_instruction + dialogue_text

    return dialogue_text + non_response_prompt

def get_extraction(
    user_message: str,
    contact_prompt: str = "",
    contact_error_count: int = 0,
    last_question: str = "",
    non_response_count: int = 0
) -> str:
    """获取信息提取提示词"""
    # 根据错误次数生成联系方式校验提示
    contact_validation_prompt = ""
    if contact_error_count > 0:
        if contact_error_count == 1:
            contact_validation_prompt = "\n\n【注意】用户刚才第1次提供了错误的联系方式，请温和地提醒重新确认。"
        elif contact_error_count == 2:
            contact_validation_prompt = "\n\n【注意】用户已第2次提供错误联系方式，可以建议用户留微信号。"
        elif contact_error_count >= 3:
            contact_validation_prompt = "\n\n【重要】用户已连续3次提供错误联系方式，说明可能不愿意提供或遇到困难。请礼貌结束对话，不要继续追问联系方式。回复示例：'嗯嗯，可能暂时不太方便呢，咱们先这样哈～'"

    # 添加上下文提示（帮助AI理解"90"是年龄还是收入，以及择偶要求的提取）
    context_prompt = ""
    if last_question:
        # 判断是否在问择偶要求
        is_asking_partner_requirement = any(keyword in last_question for keyword in
            ['想找什么样的', '择偶要求', '有什么要求', '找什么', '要求是什么', '喜欢什么样的'])

        if is_asking_partner_requirement:
            context_prompt = f"""
【⚠️⚠️重要上下文⚠️⚠️】
你刚才问的是："{last_question}"
这是在问用户的【择偶要求】！用户接下来的回答应该提取到择偶要求字段！
- 用户说数字（如"30"、"168"）→ 择偶要求（年龄/身高要求）
- 用户说"不超过30"、"30以下"→ 择偶要求:年龄不超过30岁
- 用户说"本科"、"大专"→ 择偶要求:学历要求
- 绝对不要提取到用户自己的年龄/身高/学历！
"""
        else:
            context_prompt = f"""
【上下文参考】你刚才问了："{last_question}"

【⚠️重要：部分回答识别规则⚠️】
当你问了多个问题但用户只回答部分时，根据回答内容自动匹配对应字段：
1. 【金额格式→月收入】"4万"、"5万"、"3万"、"10万"等金额格式，一定是月收入！
2. 【身高格式→身高】"180"、"175cm"、"189"等数字（100-250范围）→身高
3. 【体重格式→体重】"70kg"、"80公斤"、"90kg"等→体重
4. 【学历关键词→学历】"本科"、"硕士"、"大专"、"博士"等→学历
5. 【婚况关键词→婚况】"单身"、"离异"、"未婚"等→婚况

【示例】
- AI问"身高体重和月收入多少？"，用户答"4万"→月收入:4万（其他填null）
- AI问"身高体重多少？"，用户答"180"→身高:180cm（体重填null）
- AI问"学历和工作？"，用户答"本科"→学历:本科（职业填null）

【当前问题】请根据上述规则理解用户的回答！
"""

    # 根据无效回复次数添加额外提示
    non_response_prompt = ""
    if non_response_count >= 2:
        non_response_prompt = "\n\n【重要】用户已连续2次以上只回确认词但没有提供信息，请换其他问题询问，不要重复问同样的问题！"

    return EXTRACTION.format(
        user_message=user_message,
        contact_prompt=contact_prompt + contact_validation_prompt + non_response_prompt,
        context_prompt=context_prompt
    )

# ==================== 辅助函数 ====================
def build_gender_instruction(user_sex: Optional[str]) -> str:
    """构建性别指令"""
    if user_sex == "男":
        return "用户是男生，称呼他为小哥哥"
    elif user_sex == "女":
        return "用户是女生，称呼她为小姐姐"
    else:
        return "用户性别未知，使用'你好呀'等中性称呼"

def build_contact_instruction(contact_refused: bool) -> str:
    """构建联系方式指令"""
    if contact_refused:
        return "\n\n【重要】用户已拒绝提供联系方式，严禁再询问！"
    return ""

def build_contact_prompt(contact_collected: bool) -> str:
    """构建联系方式询问指令"""
    if not contact_collected:
        return "如果尚未收集到联系方式，适时询问用户的电话或微信"
    return "联系方式已收集，无需再询问"

def build_skipped_fields_instruction(skipped_fields: set) -> str:
    """
    构建跳过字段的指令

    Args:
        skipped_fields: 用户已跳过的字段集合

    Returns:
        str: 跳过字段的指令字符串
    """
    if not skipped_fields:
        return ""

    # 从配置获取字段名映射
    from src.config.settings import get_all_field_names
    field_name_map = get_all_field_names()

    # 转换为中文字段名
    chinese_fields = []
    for field in skipped_fields:
        if field in field_name_map:
            chinese_fields.append(field_name_map[field])

    if not chinese_fields:
        return ""

    return f"\n\n【重要】用户已表示不方便提供以下信息，严禁再询问：{', '.join(chinese_fields)}"


def build_ask_count_instruction(field_ask_count: dict, collection_progress: dict = None) -> str:
    """
    构建追问次数指令（智能追问机制）

    Args:
        field_ask_count: 各字段的追问次数 {字段名: 次数}
        collection_progress: 已收集字段的进度 {字段名: True/False}

    Returns:
        str: 追问次数的指令字符串
    """
    import logging
    logger = logging.getLogger(__name__)

    if not field_ask_count:
        return ""

    # 从配置获取字段名映射
    from src.config.settings import get_all_field_names
    field_name_map = get_all_field_names()

    # 过滤掉已收集的字段（已收集的字段不需要再追问）
    collection_progress = collection_progress or {}
    uncollected_ask_count = {
        field: count for field, count in field_ask_count.items()
        if not collection_progress.get(field, False)
    }

    if not uncollected_ask_count:
        return ""

    # 找出被问过多次的字段（未收集的）
    asked_multiple_times = []
    for field, count in uncollected_ask_count.items():
        if count >= 2 and field in field_name_map:
            asked_multiple_times.append((field_name_map[field], count))

    if not asked_multiple_times:
        # 如果有被问过1次的字段，提醒AI换种方式问
        asked_once = [(field_name_map[f], c) for f, c in uncollected_ask_count.items() if c == 1 and f in field_name_map]
        if asked_once:
            fields_str = '、'.join([f[0] for f in asked_once])
            logger.info(f"[智能追问提示] 生成换话术提示，字段: {fields_str}")
            return f"""

🚫🚫🚫【禁止直接问以下问题！已问过1次用户没回答】🚫🚫🚫
字段：{fields_str}

❌ 错误问法（禁止）：
"方便告诉我怎么称呼？" "你在哪个城市？" "你做什么工作的？"

✅ 正确问法（必须这样问，加解释说明为什么需要这个信息）：
- 称呼 → "对了小哥哥，怎么称呼你呀？告诉我名字的话，到时候匹配到合适的人可以方便称呼你～"
- 年龄 → "小哥哥年龄方便说下吗？告诉我年龄的话，可以帮你匹配年龄合适的～"
- 城市 → "小哥哥在哪个城市呀？知道你的位置才能帮你匹配同城的呢～"
- 职业 → "小哥哥做什么工作的呀？职业稳定的话会更受欢迎呢～"
- 身高 → "身高多少呀？这个信息对匹配也很重要呢～"
- 体重 → "体重方便说下吗？有些女生会比较在意这个呢～"
- 学历 → "什么学历呀？这样匹配的时候可以考虑学历相当的～"
- 月收入 → "月收入大概多少呀？这样我能帮你筛选条件相当的对象～"

📌 规则：必须先解释为什么需要这个信息，让用户理解提供信息的好处！
"""
        return ""

    # 被问过2次及以上的字段，建议暂时跳过
    skip_fields = [f[0] for f in asked_multiple_times if f[1] >= 2]
    if skip_fields:
        logger.info(f"[智能追问提示] 生成跳过提示，字段: {skip_fields}")
        return f"""

⏭️⏭️⏭️【跳过以下问题！已问过2次用户仍没回答】⏭️⏭️⏭️
字段：{'、'.join(skip_fields)}

用户可能不想回答这些问题，【必须】暂时跳过，先问其他未收集的信息！
不要反复追问同一个问题，会让用户反感。
"""

    return ""
